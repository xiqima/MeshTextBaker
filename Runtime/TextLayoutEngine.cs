        /// Call <see cref="DisposeLayout"/> when done to free those copies.
        /// </summary>
        public static ZoneLayoutResult BuildZoneExact(string text, TextZone zone, BakeSettings settings, int bakeResolution)
            => BuildZoneExact(text, zone, settings, bakeResolution, -1f);


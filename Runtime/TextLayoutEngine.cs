// Mesh Text Baker — TextLayoutEngine.cs
// Lays out TMP text for a zone and exposes the generated sub-meshes for the baker to draw
// into a RenderTexture (camera-free, via GL).
//
// Performance notes:
//   - Two reusable hidden, NON-RENDERING TextMeshPro instances are kept (one for measuring,
//     one for drawing) instead of creating/destroying a GameObject per zone. This avoids the
//     dominant per-bake cost (GameObject + TMP creation and the GC from it).
//   - The geometry of each zone is COPIED into result-owned Mesh objects (not the live shared
//     TMP mesh). This is required for correctness: the shared __MeshTextDraw TMP mesh is
//     overwritten by the next zone AND can be re-generated by an extra render pass (e.g. when
//     both the Scene and Game views render in the same frame). Drawing a live shared mesh in
//     that situation produced empty/disappearing baked text. The copied meshes are small (one
//     page of text), so the cost is negligible compared to ForceMeshUpdate.

using System;
using System.Collections.Generic;
using UnityEngine;
using TMPro;

namespace MeshTextBaker
{
    /// <summary>One drawable piece of a zone's text: a mesh + the material to draw it with.</summary>
    public struct ZoneSubMesh
    {
        public Mesh mesh;
        public Material material;
    }

    /// <summary>Result of laying out text for a zone (copied geometry, ready to draw).</summary>
    public class ZoneLayoutResult
    {
        public ZoneSubMesh[] subMeshes;
        public string renderedText;
        public int zonePixelW;
        public int zonePixelH;
        /// <summary>Inline &lt;image=…&gt; draws resolved to mesh-local rects (may be null).</summary>
        public List<InlineImageDraw> inlineImages;
        /// <summary>Warnings produced while processing inline image tags (may be null).</summary>
        public List<string> warnings;
    }

    public static class TextLayoutEngine
    {
        private const float ReferenceResolution = 1024f;

        // Reusable hidden TMP instances (measure + draw). Renderers are disabled so they never
        // appear in the scene; we only use their generated mesh data.
        private static GameObject s_MeasureGO;
        private static TextMeshPro s_MeasureTmp;
        private static GameObject s_DrawGO;
        private static TextMeshPro s_DrawTmp;
        // Calibrations (<space> pixels-per-unit, lineSpacing pixels-per-unit) run on their
        // OWN hidden instance. Sharing the measure instance interleaved probe layouts
        // ("A\nA", wide rect) between real measurements, and TMP reuses internal buffers
        // across layouts — with ShrinkToFit's rapid measure sequence that produced a
        // period-2 limit cycle (repeated Test Bakes alternated between two layouts).
        private static GameObject s_CalibGO;
        private static TextMeshPro s_CalibTmp;

        private static bool s_CleanupHooked;

        // ── Mesh pool + reusable copy buffers (GC optimization) ──
        // A bake allocated 1 Mesh + 5 Lists per zone per bake; a book page-turn does this
        // dozens of times. Meshes are rented/returned (cleared, not destroyed) and the copy
        // buffers are reused. Everything is main-thread only, like the rest of this class.
        private static readonly System.Collections.Generic.Stack<Mesh> s_MeshPool =
            new System.Collections.Generic.Stack<Mesh>(4);
        private const int MaxPooledMeshes = 8;

        private static readonly System.Collections.Generic.List<ZoneSubMesh> s_SubMeshList = new System.Collections.Generic.List<ZoneSubMesh>(4);
        private static readonly System.Collections.Generic.List<Vector3> s_VertBuf = new System.Collections.Generic.List<Vector3>(512);
        private static readonly System.Collections.Generic.List<Color32> s_ColBuf = new System.Collections.Generic.List<Color32>(512);
        private static readonly System.Collections.Generic.List<Vector4> s_Uv0Buf = new System.Collections.Generic.List<Vector4>(512);
        private static readonly System.Collections.Generic.List<Vector4> s_Uv2Buf = new System.Collections.Generic.List<Vector4>(512);
        private static readonly System.Collections.Generic.List<int> s_TriBuf = new System.Collections.Generic.List<int>(768);

        private static Mesh RentMesh()
        {
            while (s_MeshPool.Count > 0)
            {
                var pooled = s_MeshPool.Pop();
                if (pooled != null) return pooled; // may have been destroyed externally
            }
            return new Mesh { name = "MTB_ZoneMesh", hideFlags = HideFlags.HideAndDontSave };
        }

        private static void ReturnMesh(Mesh mesh)
        {
            if (mesh == null) return;
            if (s_MeshPool.Count >= MaxPooledMeshes)
            {
                if (Application.isPlaying) UnityEngine.Object.Destroy(mesh);
                else UnityEngine.Object.DestroyImmediate(mesh);
                return;
            }
            mesh.Clear();
            s_MeshPool.Push(mesh);
        }

        private static TextMeshPro GetTmpInstance(ref GameObject go, ref TextMeshPro tmp, string name)
        {
            if (tmp != null) return tmp;
            HookCleanup();
            go = new GameObject(name) { hideFlags = HideFlags.HideAndDontSave };
            tmp = go.AddComponent<TextMeshPro>();
            var r = go.GetComponent<Renderer>();
            if (r != null) r.enabled = false; // never render into the scene
            return tmp;
        }

        /// <summary>
        /// Disables ALL renderers under the hidden TMP object. TMP lazily spawns CHILD sub-mesh
        /// objects (TMP_SubMesh) for fallback fonts / sprite assets during ForceMeshUpdate; their
        /// renderers are enabled by default and would draw stray glyphs into the scene at the
        /// origin. Must be called after every ForceMeshUpdate (new children may have appeared).
        /// </summary>
        private static void DisableChildRenderers(GameObject go)
        {
            if (go == null) return;
            var renderers = go.GetComponentsInChildren<Renderer>(true);
            for (int i = 0; i < renderers.Length; i++)
                renderers[i].enabled = false;
        }

        /// <summary>Applies word-wrapping in a TMP-version-agnostic way (2022.3 LTS ↔ 2023+).</summary>
        private static void SetWordWrap(TextMeshPro tmp)
        {
#if TMP_3_2_OR_NEWER
            tmp.textWrappingMode = TextWrappingModes.Normal;
#else
            // Legacy TMP 3.0.x API (obsoleted once textWrappingMode exists).
#pragma warning disable 618
            tmp.enableWordWrapping = true;
#pragma warning restore 618
#endif
        }

        private static void HookCleanup()
        {
            if (s_CleanupHooked) return;
            s_CleanupHooked = true;
            Application.quitting += DestroyHiddenInstances;
#if UNITY_EDITOR
            UnityEditor.AssemblyReloadEvents.beforeAssemblyReload += DestroyHiddenInstances;
#endif
        }

        /// <summary>Destroys the shared hidden TMP instances (called on quit / assembly reload).</summary>
        public static void DestroyHiddenInstances()
        {
            if (s_MeasureGO != null)
            {
                if (Application.isPlaying) UnityEngine.Object.Destroy(s_MeasureGO);
                else UnityEngine.Object.DestroyImmediate(s_MeasureGO);
            }
            if (s_DrawGO != null)
            {
                if (Application.isPlaying) UnityEngine.Object.Destroy(s_DrawGO);
                else UnityEngine.Object.DestroyImmediate(s_DrawGO);
            }
            if (s_CalibGO != null)
            {
                if (Application.isPlaying) UnityEngine.Object.Destroy(s_CalibGO);
                else UnityEngine.Object.DestroyImmediate(s_CalibGO);
            }
            s_MeasureGO = null; s_MeasureTmp = null;
            s_DrawGO = null; s_DrawTmp = null;
            s_CalibGO = null; s_CalibTmp = null;

            InlineImageParser.ReleaseFileCache();
            InlineFontResolver.ReleaseFileCache();

            // Drop pooled meshes too — they reference the reloading domain.
            while (s_MeshPool.Count > 0)
            {
                var mesh = s_MeshPool.Pop();
                if (mesh == null) continue;
                if (Application.isPlaying) UnityEngine.Object.Destroy(mesh);
                else UnityEngine.Object.DestroyImmediate(mesh);
            }
        }

        /// <summary>
        /// Returns how many characters of 'text' fit in the slot by height, in a single TMP pass.
        /// Reads line/character info; does not collect meshes. Measurement only.
        /// </summary>
        public static int MeasureFittingChars(string text, TextZone slot, BakeSettings settings, int bakeResolution)
            => MeasureFittingChars(text, slot, settings, bakeResolution, bakeResolution, -1f);

        /// <summary>
        /// Non-square variant: measures against a WxH bake target (e.g. a custom NPOT
        /// background texture). Old square callers keep working unchanged.
        /// </summary>
        public static int MeasureFittingChars(string text, TextZone slot, BakeSettings settings,
            int bakeW, int bakeH)
            => MeasureFittingChars(text, slot, settings, bakeW, bakeH, -1f);

        /// <summary>
        /// Same as <see cref="MeasureFittingChars(string,TextZone,BakeSettings,int)"/> but with an
        /// explicit pixel font size (used by ShrinkToFit's binary search). Pass a value &lt;= 0 to
        /// use the zone's own resolved size.
        /// </summary>
        public static int MeasureFittingChars(string text, TextZone slot, BakeSettings settings,
            int bakeResolution, float pixelFontSizeOverride)
            => MeasureFittingChars(text, slot, settings, bakeResolution, bakeResolution, pixelFontSizeOverride);

        /// <summary>
        /// Same as <see cref="MeasureFittingChars(string,TextZone,BakeSettings,int,float)"/> but
        /// against a WxH bake target. Absolute font sizes scale with the LONG side.
        /// </summary>
        public static int MeasureFittingChars(string text, TextZone slot, BakeSettings settings,
            int bakeW, int bakeH, float pixelFontSizeOverride)
        {
            if (string.IsNullOrEmpty(text)) return 0;

            Rect padded = slot.GetPaddedPixelRect(bakeW, bakeH);
            int zoneW = Mathf.Max(2, Mathf.RoundToInt(padded.width));
            int zoneH = Mathf.Max(2, Mathf.RoundToInt(padded.height));

            TMP_FontAsset font = slot.fontOverride != null ? slot.fontOverride : settings.defaultFont;
            if (font == null) font = TMP_Settings.defaultFontAsset;
            if (font == null) return text.Length;

            float fontSize = pixelFontSizeOverride > 0f
                ? pixelFontSizeOverride
                : ResolveZonePixelFontSize(slot, settings, zoneH, bakeW, bakeH);

            // Inline <image> tags: measure the PROCESSED text (anchor + spacing occupy real
            // layout space) but return an index in the SOURCE string via segment mapping —
            // page slicing then keeps tags intact (book support).
            List<ImageTagSegment> imageSegments = null;
            string measured = text;
            if (slot.richTextEnabled && InlineImageParser.HasImageTags(text))
            {
                imageSegments = new List<ImageTagSegment>(4);
                float spaceFactor = GetSpacePixelFactor(font, fontSize);
                measured = InlineImageParser.ProcessWithMap(text, fontSize, settings.imageLibrary,
                    null, null, imageSegments, spaceFactor);
            }

            // Opacity is deliberately NOT expanded during measurement: alpha has no layout
            // cost, while injecting TMP <alpha> tags here would shift source indices used by
            // book pagination and inline-image segment mapping.
            var tmp = GetTmpInstance(ref s_MeasureGO, ref s_MeasureTmp, "__MeshTextMeasure");
            var rt = tmp.rectTransform;
            rt.sizeDelta = new Vector2(zoneW, zoneH);

            tmp.font = font;
            tmp.fontSize = fontSize;
            tmp.lineSpacing = ResolveLineSpacingUnits(font, fontSize, slot.lineSpacing);
            tmp.enableAutoSizing = false;
            // Measure in TopLeft space so fitting is independent of the zone's vertical anchor.
            // The final render still uses the authored Top/Middle/Bottom alignment.
            tmp.alignment = TMPro.TextAlignmentOptions.TopLeft;
            tmp.richText = slot.richTextEnabled;
            tmp.overflowMode = TextOverflowModes.Overflow;
            SetWordWrap(tmp);

            tmp.text = measured;
            tmp.ForceMeshUpdate(true);
            DisableChildRenderers(s_MeasureGO); // TMP may spawn enabled sub-mesh children

            var info = tmp.textInfo;
            if (info.characterCount == 0) return 0;
            if (info.lineCount == 0) return text.Length;

            float bottomLimit = -zoneH * 0.5f;
            float topLimit = zoneH * 0.5f;
            int lastFittingChar = -1;
            for (int li = 0; li < info.lineCount; li++)
            {
                // Checking only descender worked for Top alignment but let Bottom/Middle blocks
                // grow above the zone. Both vertical bounds must fit.
                if (info.lineInfo[li].descender < bottomLimit ||
                    info.lineInfo[li].ascender > topLimit) break;
                lastFittingChar = info.lineInfo[li].lastCharacterIndex;
            }

            if (lastFittingChar < 0) return 0;
            if (lastFittingChar >= info.characterCount - 1) return text.Length;

            int fitIndex = info.characterInfo[lastFittingChar].index + 1;
            // Map back from the processed (anchor/spacing) string to the source string.
            if (imageSegments != null)
                fitIndex = InlineImageParser.MapProcessedToSource(fitIndex, imageSegments);
            return Mathf.Clamp(fitIndex, 0, text.Length);
        }

        /// <summary>
        /// Lays out exactly the given (already-sliced) text and returns its sub-meshes in a single
